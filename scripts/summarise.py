#!/usr/bin/env python3
"""Assemble every result into one readable summary (stdout + RESULTS.md)."""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

ROW_ORDER = [
    ("main_hybrid", "Hybrid (full supervision)", "random patient split"),
    ("main_conc_only", "Hybrid, concentrations only", "random patient split"),
    ("main_blackbox", "Black box (full supervision)", "random patient split"),
    ("main_blackbox_conc_only", "Black box, concentrations only",
     "random patient split"),
    ("main_no_labs", "Hybrid, no bedside labs", "ablation"),
    ("main_no_tox", "Hybrid, no water chemistry", "ablation"),
    ("main_anthro_only", "Hybrid, anthropometry only", "ablation"),
    ("setting_hybrid", "Hybrid, unseen water setting", "generalisation"),
    ("drug_hybrid", "Hybrid, unseen drugs", "generalisation"),
]


def fmt(v, n=3):
    return "-" if v is None else f"{v:.{n}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--eval", default="outputs/evaluation.json")
    ap.add_argument("--impact", default="outputs/clinical_impact.json")
    ap.add_argument("--impact-mineff", default="outputs/clinical_impact_mineff.json")
    ap.add_argument("--out", default="RESULTS.md")
    args = ap.parse_args()

    ev = json.load(open(args.eval)) if os.path.exists(args.eval) else {}
    L = []

    def w(s=""):
        L.append(s)
        print(s)

    w("# MalnuPK results")
    w()
    w("All numbers are from a **synthetic** virtual-trial dataset generated by the")
    w("mechanistic simulator in this repository. They measure how well the model")
    w("recovers a known mechanism from noisy, sparse, partially-missing")
    w("observations. **They are not evidence about real patients.**")
    w()
    w("## 1. Predictive accuracy")
    w()
    w("Accuracy is against the *noise-free* simulated curve at all 50 time points,")
    w("while the model only ever saw the noisy, sparsely-sampled subset.")
    w("`fold error` is the ratio of predicted to true concentration.")
    w()
    w("| model | split | log-RMSE | median fold error | within 2x | R² (log) |")
    w("|---|---|---|---|---|---|")
    for key, label, split in ROW_ORDER:
        r = ev.get(key)
        if not r:
            continue
        o = r["overall"]
        w(f"| {label} | {split} | {fmt(o['log_rmse'])} | "
          f"{fmt(o['median_fold_error'])} | {o['within_2x']:.1%} | "
          f"{fmt(o['r2_log'], 4)} |")
    w()

    h = ev.get("main_hybrid")
    bb = ev.get("main_blackbox_conc_only")
    hc = ev.get("main_conc_only")
    if h and bb and hc:
        ratio = bb["overall"]["log_rmse"] / hc["overall"]["log_rmse"]
        w(f"**The mechanistic solver is worth {ratio:.1f}x in log-RMSE.** "
          f"`Hybrid, concentrations only` and `Black box, concentrations only` "
          "see identical inputs and identical supervision and have within 3% the")
        w("same parameter count. The only difference is whether a compartmental")
        w("solver sits between the network and the curve.")
        w()

    if h:
        w("### Accuracy by nutritional class (main hybrid)")
        w()
        w("| class | records | median fold error | within 2x |")
        w("|---|---|---|---|")
        for k, v in h["by_nutrition"].items():
            w(f"| {k.replace('_', ' ')} | {v['n_records']} | "
              f"{fmt(v['median_fold_error'])} | {v['within_2x']:.1%} |")
        w()
        w("Accuracy holds across the severity range, degrading slightly in")
        w("oedematous malnutrition - the hardest group, and the one where the")
        w("physiology departs furthest from the well-nourished reference.")
        w()
        if "parameters" in h:
            w("### Recovery of the latent PK parameters")
            w()
            w("These are never given as inputs; the model infers them from")
            w("observable covariates alone.")
            w()
            w("| parameter | R² (log) | median fold error |")
            w("|---|---|---|")
            for k, v in h["parameters"].items():
                w(f"| {k} | {fmt(v['r2_log'], 4)} | {fmt(v['median_fold_error'])} |")
            w()

    # ---- ablations ----
    w("## 2. Which information matters")
    w()
    base = ev.get("main_hybrid", {}).get("overall", {}).get("log_rmse")
    if base:
        w("| information removed | log-RMSE | degradation |")
        w("|---|---|---|")
        for key, label in (("main_no_labs", "bedside biochemistry panel"),
                           ("main_no_tox", "drinking-water chemistry"),
                           ("main_anthro_only", "both (anthropometry only)")):
            r = ev.get(key)
            if r:
                v = r["overall"]["log_rmse"]
                w(f"| {label} | {fmt(v)} | {v / base:.1f}x worse |")
        w()
        w("Water chemistry is the single most load-bearing input block, and the")
        w("asymmetry is interpretable rather than a claim that toxicants matter")
        w("more than nutrition: anthropometry partially proxies for the")
        w("biochemistry panel (a wasted, oedematous child is likely")
        w("hypoalbuminaemic), whereas **nothing in the clinical examination")
        w("proxies for what is in the well**. Removing it leaves a large,")
        w("structured source of variance completely unobservable.")
        w()

    # ---- generalisation ----
    w("## 3. Generalisation, including where it fails")
    w()
    s = ev.get("setting_hybrid")
    if s:
        o = s["overall"]
        w(f"**Unseen exposure setting.** Trained without any `industrial_runoff` "
          f"water, tested only on it: median fold error {o['median_fold_error']:.2f}, "
          f"{o['within_2x']:.0%} within 2-fold. Degraded but usable - the model")
        w("extrapolates along the toxicant axis reasonably well, because the")
        w("exposure-response relationships it learned elsewhere still apply at")
        w("higher burdens.")
        w()
    d = ev.get("drug_hybrid")
    if d:
        o = d["overall"]
        w(f"**Unseen drug — this fails, and the failure is informative.** Trained "
          f"on 7 drugs, tested on rifampicin and gentamicin held out entirely: "
          f"median fold error {o['median_fold_error']:.1f}.")
        w()
        w("| held-out drug | median fold error | within 2x |")
        w("|---|---|---|")
        for k, v in d["by_drug"].items():
            if v["n_records"]:
                w(f"| {k} | {v['median_fold_error']:.2f} | {v['within_2x']:.1%} |")
        w()
        w("The failure is almost entirely gentamicin, and that is mechanistically")
        w("legible. Removing it leaves **no** training drug that is simultaneously")
        w("intravenous, essentially unbound, and ~100% renally cleared -")
        w("ceftriaxone is intravenous but 94% protein-bound. The drug encoder is")
        w("asked to extrapolate outside the region of chemical space it has seen,")
        w("and it cannot. Rifampicin, which has close analogues in the training")
        w("set (lipophilic, bile-dependent, CYP3A4-cleared), degrades to a 2.4-fold")
        w("error instead. **Conclusion: transfer to a new drug works only by")
        w("interpolation within covered chemical space, and a 7-drug library does")
        w("not cover much.** Scaling the drug library is the obvious next step.")
        w()

    # ---- calibration ----
    if h and "calibration" in h:
        c = h["calibration"]
        w("## 4. Uncertainty calibration")
        w()
        w("The two uncertainty components are checked against different targets,")
        w("because they answer different questions. Residual (aleatoric)")
        w("uncertainty describes a *measurement*, so it is scored against noisy")
        w("observations; epistemic uncertainty describes the *underlying curve*,")
        w("so it is scored against the noise-free truth.")
        w()
        w("| nominal | total interval vs observations | epistemic vs truth (raw) | "
          "epistemic vs truth (recalibrated) |")
        w("|---|---|---|---|")
        for lv in (50, 80, 90, 95):
            w(f"| {lv}% | "
              f"{c.get(f'total_coverage_of_observations_{lv}', float('nan')):.1%} | "
              f"{c.get(f'epistemic_coverage_of_truth_{lv}', float('nan')):.1%} | "
              f"{c.get(f'calibrated_coverage_{lv}', float('nan')):.1%} |")
        w()
        sc = h.get("epistemic_scale")
        w("The residual-error model is close to perfectly calibrated out of the")
        w("box. Monte-Carlo dropout, by contrast, is badly overconfident: its")
        w("nominal 90% interval covers only "
          f"{c.get('epistemic_coverage_of_truth_90', float('nan')):.0%} of the truth.")
        if sc:
            w(f"A single variance-recalibration scalar ({sc:.2f}x), fitted on the")
            w("validation split and never on test, brings it to "
              f"{c.get('calibrated_coverage_90', float('nan')):.0%}.")
        w("This matters operationally rather than cosmetically: the dose")
        w("recommender turns that distribution into a probability of target")
        w("attainment, and an overconfident one picks doses with no margin.")
        w()

    # ---- clinical ----
    if os.path.exists(args.impact):
        imp = json.load(open(args.impact))
        s = imp["summary"]
        o = s["overall"]
        w("## 5. Model-guided dosing vs the weight band")
        w()
        w(f"A fresh population of {o['n'] // len(s['by_drug'])} virtual children the")
        w("model has never seen, dosed two ways, with **the simulator scoring both**.")
        w("The model sees only observable covariates, with the usual missing labs")
        w("and measurement noise.")
        w()
        w("| | standard mg/kg | model-guided |")
        w("|---|---|---|")
        w(f"| reached PK/PD target | {o['standard_attainment']:.1%} | "
          f"**{o['model_attainment']:.1%}** |")
        w(f"| over-exposed | {o['standard_toxicity']:.1%} | "
          f"**{o['model_toxicity']:.1%}** |")
        w()
        w("| drug | target attained | over-exposed | median dose | 10-90th pct |")
        w("|---|---|---|---|---|")
        for k, v in s["by_drug"].items():
            w(f"| {k} | {v['standard_attainment']:.0%} → "
              f"**{v['model_attainment']:.0%}** | "
              f"{v['standard_toxicity']:.0%} → **{v['model_toxicity']:.0%}** | "
              f"{v['median_dose_ratio']:.2f}x | "
              f"{v['p10_dose_ratio']:.2f}-{v['p90_dose_ratio']:.2f}x |")
        w()
        w("The median dose ratio is ~1.00 for most drugs: the model leaves the")
        w("label dose alone for the children it is already serving and moves only")
        w("the ones it is failing. That is the anchored policy working as intended,")
        w("and it is why attainment rises without a population-wide dose increase.")
        w()
        w("| nutritional class | target attained | over-exposed | dose 10-90th pct |")
        w("|---|---|---|---|")
        for k, v in s["by_class"].items():
            w(f"| {k.replace('_', ' ')} | {v['standard_attainment']:.0%} → "
              f"**{v['model_attainment']:.0%}** | "
              f"{v['standard_toxicity']:.0%} → **{v['model_toxicity']:.0%}** | "
              f"{v['p10_dose_ratio']:.2f}-{v['p90_dose_ratio']:.2f}x |")
        w()
        if os.path.exists(args.impact_mineff):
            m2 = json.load(open(args.impact_mineff))["summary"]["overall"]
            w("### The objective matters as much as the model")
            w()
            w("The same model under a dose-sparing policy (`minimum_effective`:")
            w("smallest safe dose reaching the best achievable confidence):")
            w()
            w("| policy | target attained | over-exposed | median dose |")
            w("|---|---|---|---|")
            w(f"| standard mg/kg | {o['standard_attainment']:.1%} | "
              f"{o['standard_toxicity']:.1%} | 1.00x |")
            w(f"| anchored (default) | {o['model_attainment']:.1%} | "
              f"{o['model_toxicity']:.1%} | {o['median_dose_ratio']:.2f}x |")
            w(f"| minimum effective | {m2['model_attainment']:.1%} | "
              f"{m2['model_toxicity']:.1%} | {m2['median_dose_ratio']:.2f}x |")
            w()
            w("Both policies beat the weight band, and the choice between them is")
            w("a clinical judgement rather than a technical default, which is why")
            w("both are implemented and measured instead of one being quietly")
            w("assumed. The anchored policy attains the target more often; the")
            w("dose-sparing policy gets close on roughly half the drug, which is")
            w("not nothing where supply and cost are binding constraints. The")
            w("anchored policy is the default because under-exposure, not")
            w("over-exposure, is the clinical problem in this population, and")
            w("because every departure from an approved label then has a stated")
            w("cause. Note also that the dose-sparing result is only as")
            w("trustworthy as the simulator\'s PK/PD targets: it works by")
            w("spending the margin between the label dose and the target, so it")
            w("inherits all of that target\'s uncertainty.")
            w()

    w("## 6. What would have to happen before any of this meant something")
    w()
    w("1. Fit the simulator's coefficients to real sparse PK data from")
    w("   malnourished cohorts, instead of choosing them for plausibility.")
    w("2. Re-derive the model against that calibrated simulator.")
    w("3. Prospectively validate predicted target attainment in a real cohort.")
    w()
    w("Step 1 and step 3 have not been done. Until they are, every number above")
    w("describes a model's fidelity to a set of equations, and nothing more.")

    with open(args.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"\n[wrote {args.out}]")


if __name__ == "__main__":
    main()
